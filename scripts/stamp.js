// Cache-busting for GitHub Pages, which serves every file with a 10-minute cache. Each script and
// the stylesheet is linked from index.html with a hash of its contents (?v=…), and an import map
// does the same for the modules app.js imports, so a reload always gets a matching set of files
// and unchanged files stay cached. Run `npm run stamp` after changing any of them; the tests fail
// until you do.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const START = '<!-- assets:start (generated by npm run stamp) -->';
const END = '<!-- assets:end -->';

const hash = (path) => createHash('sha256').update(readFileSync(join(ROOT, path))).digest('hex').slice(0, 10);

/** The stylesheet link, import map and app script for the current files. */
export function assetBlock() {
  const modules = readdirSync(join(ROOT, 'js')).filter((f) => f.endsWith('.js')).sort().map((f) => `js/${f}`);
  const imports = Object.fromEntries(modules.map((m) => [`./${m}`, `./${m}?v=${hash(m)}`]));
  return [
    START,
    `  <link rel="stylesheet" href="css/styles.css?v=${hash('css/styles.css')}">`,
    `  <script type="importmap">${JSON.stringify({ imports }, null, 2).replace(/\n/g, '\n  ')}</script>`,
    `  <script type="module" src="js/app.js?v=${hash('js/app.js')}"></script>`,
    `  ${END}`,
  ].join('\n');
}

/** index.html with the asset block brought up to date. */
export function stamped(html = readFileSync(join(ROOT, 'index.html'), 'utf8')) {
  const from = html.indexOf(START);
  const to = html.indexOf(END);
  if (from < 0 || to < 0) throw new Error('index.html has no assets block to stamp');
  return html.slice(0, from) + assetBlock() + html.slice(to + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const before = readFileSync(join(ROOT, 'index.html'), 'utf8');
  const after = stamped(before);
  if (after === before) console.log('index.html is already up to date.');
  else { writeFileSync(join(ROOT, 'index.html'), after); console.log('index.html stamped.'); }
}
