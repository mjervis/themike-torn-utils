import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { stamped } from '../scripts/stamp.js';

test('index.html links every script and the stylesheet at its current version (run `npm run stamp`)', () => {
  const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
  assert.ok(html === stamped(html), 'index.html is out of date — run `npm run stamp` and commit the result');
});

test('stamped() replaces only the assets block', () => {
  const html = 'before\n<!-- assets:start (generated by npm run stamp) -->old<!-- assets:end -->\nafter';
  const out = stamped(html);
  assert.ok(out.startsWith('before\n<!-- assets:start'));
  assert.ok(out.endsWith('<!-- assets:end -->\nafter'));
  assert.match(out, /"\.\/js\/oc\.js": "\.\/js\/oc\.js\?v=[0-9a-f]{10}"/);
  assert.match(out, /<script type="module" src="js\/app\.js\?v=[0-9a-f]{10}"><\/script>/);
  assert.throws(() => stamped('no block here'));
});
